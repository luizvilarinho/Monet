// Sem protótipo: um nome gravado como "toString" cai no padrão.
export const TYPE_ICONS: Record<string, Icon> = Object.assign(
  Object.create(null),
  ...TYPE_ICON_GROUPS.map((g) => g.icons)
)

export function TypeIcon({ name, size = 13 }: { name: string | null; size?: number }) {
  const Glyph = (name && TYPE_ICONS[name]) || Note
  return <Glyph size={size} aria-hidden />
}
