import { COMMANDS, findCommand } from '../../lib/commands'
import { agentLabel } from '../../lib/agents'

export type CommandLineStatus =
  | 'idle'
  | 'draft'
  | 'valid'
  | 'invalid'
  | 'incomplete'
  | 'executed'

export interface ParsedCommandLine {
  raw: string
  trimmed: string
  commandName: string
  query: string
  isIsolated: boolean
  definition: ReturnType<typeof findCommand>
}

const COMMAND_NAMES = COMMANDS.map((command) => command.name)

const TITLE_QUERY_MAX = 40

// Rótulo do agente; com query, "<rótulo> · <query curta>" (corte em ~40
// caracteres), para distinguir os blocos do mesmo comando na nota.
export function getToggleTitle(command: string, query?: string): string {
  const label = agentLabel(command)
  const q = query?.replace(/\s+/g, ' ').trim() ?? ''
  if (!q) return label
  return `${label} · ${q.length > TITLE_QUERY_MAX ? `${q.slice(0, TITLE_QUERY_MAX - 1).trimEnd()}…` : q}`
}

// Título do bloco no texto que vai para a IA (e no export): sempre diz que foi
// gerado pela IA. O rótulo curto ("Glossary", "Today"…) fica só na tela.
export function getAiBlockTitle(command: string, query?: string): string {
  const title = getToggleTitle(command, query)
  return /generated by AI/i.test(agentLabel(command)) ? title : `${title} (generated by AI)`
}

// "/" sozinho ou "/nome" (letra, depois letras, números e hífen) seguido de
// espaço ou do fim. Caminho ("/usr/bin"), fração ("/2") e "/notas.md" ficam
// texto comum, sem cor nem erro de comando.
const COMMAND_LINE_RE = /^\s*\/(?:[a-z][a-z0-9-]*)?(?:\s|$)/i

export function isPotentialCommandLine(line: string): boolean {
  return COMMAND_LINE_RE.test(line)
}

export function parseCommandLine(line: string): ParsedCommandLine | null {
  if (!isPotentialCommandLine(line)) return null
  const trimmed = line.trim()
  const match = trimmed.match(/^(\/[^\s]+)(?:\s+(.*))?$/)
  if (!match) {
    return {
      raw: line,
      trimmed,
      commandName: trimmed,
      query: '',
      isIsolated: true,
      definition: undefined,
    }
  }
  const commandName = match[1].toLowerCase()
  const query = (match[2] ?? '').trim()
  return {
    raw: line,
    trimmed,
    commandName,
    query,
    isIsolated: true,
    definition: findCommand(commandName),
  }
}

export function getCommandLineStatus(line: string, isCalendarNote = false): CommandLineStatus {
  const parsed = parseCommandLine(line)
  if (!parsed) return 'idle'
  if (!parsed.definition) return 'invalid'
  if (parsed.definition.calendarOnly && !isCalendarNote) return 'invalid'
  if (parsed.definition.takesQuery && !parsed.definition.optionalQuery && parsed.query.length === 0) {
    return 'incomplete'
  }
  return 'valid'
}

// Grupos do autocomplete, nesta ordem. Comando fora deles cai em "More".
const COMMAND_GROUPS: Array<{ label: string; names: string[] }> = [
  { label: 'Understand', names: ['/define', '/explain', '/docs', '/ask', '/guide'] },
  { label: 'Review', names: ['/critique', '/expand', '/opinion'] },
  { label: 'Transform', names: ['/summarize', '/table', '/mindmap', '/action'] },
  { label: 'Web', names: ['/search', '/profile'] },
  { label: 'Calendar', names: ['/today', '/week-review'] },
  { label: 'Blocks', names: ['/tasks', '/diagram'] },
]
const OTHER_GROUP = 'More'

export function commandGroup(name: string): string {
  return COMMAND_GROUPS.find((g) => g.names.includes(name))?.label ?? OTHER_GROUP
}

// Posição na lista agrupada (grupo, depois a ordem dentro dele).
function groupRank(name: string): number {
  const gi = COMMAND_GROUPS.findIndex((g) => g.names.includes(name))
  return gi < 0 ? COMMAND_GROUPS.length * 100 : gi * 100 + COMMAND_GROUPS[gi].names.indexOf(name)
}

export function getCommandSuggestions(input: string, isCalendarNote = false): string[] {
  const normalized = input.trim().toLowerCase()
  const availableNames = isCalendarNote
    ? COMMAND_NAMES
    : COMMAND_NAMES.filter((name) => !findCommand(name)?.calendarOnly)
  if (!normalized.startsWith('/')) return []
  const matches =
    normalized === '/' ? availableNames : availableNames.filter((name) => name.toLowerCase().startsWith(normalized))
  return [...matches].sort((a, b) => groupRank(a) - groupRank(b))
}

// Dica da linha com comando inválido ou incompleto (decoração cinza no fim).
export function commandLineHint(line: string, status: 'invalid' | 'incomplete'): string {
  const def = parseCommandLine(line)?.definition
  if (status === 'incomplete' && def) return `${def.name} needs a query · e.g. ${def.example}`
  if (def?.calendarOnly) return `${def.name} works in Calendar notes`
  return 'Unknown command · type / to see the list'
}
