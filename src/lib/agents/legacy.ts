import type { AgentDef, ContextPolicy, WebPolicy } from './core'

// Comandos fora da lista de agentes (D17): mesmo comportamento de antes, com
// o núcleo comum, as regras de "complementar a nota" e a própria linha de
// comportamento (vazia = só a descrição do comando, na mensagem do usuário).

function legacyContext(web: WebPolicy): ContextPolicy {
  return {
    note: 'full',
    noteMeta: false,
    rag: { pipeline: 'vector', topK: 5 },
    web,
    agenda: null,
    datedNotes: true,
    previousDefinition: false,
  }
}

