import type { AgentDef } from './core'
import { critiqueAgent } from './critique'
import { defineAgent } from './define'
import { docsAgent } from './docs'
import { expandAgent } from './expand'
import {
  actionAgent,
  askAgent,
  explainAgent,
  guideAgent,
  mindmapAgent,
  opinionAgent,
  profileAgent,
  searchAgent,
  summarizeAgent,
  tableAgent,
} from './legacy'
import { todayAgent } from './today'
import { weekReviewAgent } from './weekReview'

// Registro dos agentes de slash, na ordem do autocomplete.
export const AGENTS: AgentDef[] = [
  searchAgent,
  profileAgent,
  defineAgent,
  critiqueAgent,
  summarizeAgent,
  opinionAgent,
  tableAgent,
  expandAgent,
  explainAgent,
  guideAgent,
  mindmapAgent,
  askAgent,
  docsAgent,
  actionAgent,
  weekReviewAgent,
  todayAgent,
]

export function findAgent(name: string): AgentDef | undefined {
  const key = name.toLowerCase()
  return AGENTS.find((a) => a.command.name.toLowerCase() === key)
}

// Nomes antigos em PT gravados em `ai_responses.command`.
const OLD_COMMAND_NAMES: Record<string, string> = {
  '/pesquisa': '/search', '/quem': '/profile', '/definir': '/define', '/resumir': '/summarize',
  '/opiniao': '/opinion', '/tabela': '/table', '/aprofundar': '/expand', '/explicar': '/explain',
  '/guia': '/guide', '/mapa-mental': '/mindmap', '/perguntar': '/ask', '/documentos': '/docs',
}

// Comandos que saíram, com blocos ainda gravados nas notas.
const RETIRED_LABELS: Record<string, string> = {
  '/week': 'Week summary generated by AI',
  '/planner': 'Plan generated by AI',
}

// Rótulo do bloco de IA de um comando (atual, antigo em PT ou aposentado).
export function agentLabel(command: string): string {
  const name = OLD_COMMAND_NAMES[command] ?? command
  return findAgent(name)?.label ?? RETIRED_LABELS[name] ?? 'Response generated by AI'
}
